for _key, _record in {**CONTENT, **WEB_CONTENT}.items():
    _theory, _code, _explanation, _remember, _practice, _criteria, _exercises = _record
    LESSONS[_key] = Lesson(_theory, _code, _explanation,
                           tuple(Exercise(*exercise) for exercise in _exercises),
                           _remember, _practice, _criteria)

for _key, (_remember, _practice, _criteria) in INTRO_PRACTICE.items():
    LESSONS[_key] = replace(LESSONS[_key], remember=_remember,
                            practice=_practice, criteria=_criteria)


def check_answer(exercise, answer):
    """Ignore accidental outer whitespace, preserve meaningful case and spacing."""
    return answer.strip() == exercise.answer
